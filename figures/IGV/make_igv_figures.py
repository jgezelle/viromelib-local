#!/usr/bin/env python3
"""
make_igv_figures.py
===================

Reproducible IGV panels for the figures (run log step 19).

This does not replace RZ's two scripts, it drives them:

  fragments_to_tracks.py  fragment TSV -> 5'-end bedGraph (+ tile BED, BEDPE).  Run once per library.
  make_igv_session.py     a set of track files -> one session XML.

What this adds on top, and why each part is needed for a figure rather than for browsing:

1. **A locked, shared data range across all six libraries.** IGV autoscales each track independently by
   default, which is exactly what made the astrovirus look like an X-specific peak when it was not: a
   213-read bump autoscaled to full panel height next to an R track scaled to thousands. Every bedGraph
   track in the session is written with an explicit `<DataRange>`, by default the maximum 5'-end count seen
   at that locus across **all** libraries, so X and R are directly comparable and the figure cannot lie
   about relative height. `--ymax-mode` chooses how that number is picked; the value used is printed and
   recorded per locus.

2. **One session per locus**, so a figure panel is a file, not a sequence of clicks.

3. **An IGV batch script** that opens each session, goes to the locus and writes a PNG and an SVG. Panels
   are then regenerated by re-running one command instead of re-screenshotting.

4. **Locus resolution from the site table.** Give it accessions (or site IDs) and it finds the feature each
   site sits on and the feature's length, so the locus string is right without hand-typing
   `NC_024701.1|6427-6598_inferred_3UTR:1-171`.

Track order in the session follows the sample sheet convention used throughout: R1 R2 R3 X1 X2 X3, controls
first, so the eye reads control-then-treated down the panel.

usage
-----
  # one session + batch entry per accession
  make_igv_figures.py --genome ORDERED_FA --bed-tiles ORDERED_BED \\
      --bedgraph R1.bedgraph R2.bedgraph R3.bedgraph X1.bedgraph X2.bedgraph X3.bedgraph \\
      --labels R1 R2 R3 X1 X2 X3 \\
      --sites-csv SITES_FINAL.csv --accessions NC_015843.2 NC_012532.1 \\
      --gtf SITES.gtf --bed SITES.bed \\
      --out-dir work/09_igv/figures_261020

  # every site in the table that has a CM hit
  make_igv_figures.py ... --sites-csv SITES.csv --where-cm-hit
"""
import argparse
import collections
import csv
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET

# ─────────────────────────────────────────────────────────────── bedGraph reading


def read_bedgraph(path):
    """-> {feature: {pos: value}}. Skips `track`/`browser` directives."""
    out = collections.defaultdict(dict)
    with open(path) as fh:
        for line in fh:
            if not line.strip() or line.startswith(("track", "browser", "#")):
                continue
            f = line.split("\t")
            if len(f) < 4:
                continue
            try:
                out[f[0]][int(f[1])] = float(f[3])
            except ValueError:
                continue
    return out


def locus_max(bgs, feature, start=None, end=None):
    """Highest 5'-end value on `feature` across all bedGraphs, optionally within [start, end)."""
    m = 0.0
    for bg in bgs:
        for pos, v in bg.get(feature, {}).items():
            if start is not None and not (start <= pos < end):
                continue
            m = max(m, v)
    return m


# ─────────────────────────────────────────────────────────────── locus resolution


def feature_lengths(bed_path):
    """Feature -> length, from the tile BED: the largest tile end on that feature.
    The ordered reference keeps features untrimmed, so the last tile end is <= the feature length;
    using it as the locus end shows the tiled extent, which is what the assay measured."""
    L = {}
    with open(bed_path) as fh:
        for line in fh:
            f = line.rstrip("\n").split("\t")
            if len(f) >= 3:
                try:
                    L[f[0]] = max(L.get(f[0], 0), int(f[2]))
                except ValueError:
                    continue
    return L


def resolve_loci(a):
    """-> list of dicts: feature, start, end, label, note. One entry per figure panel."""
    lens = feature_lengths(a.bed_tiles)

    # explicit feature:start-end strings need no table
    if a.locus:
        out = []
        for s in a.locus:
            m = re.match(r"^(.*?):(\d+)-(\d+)$", s)
            if m:
                out.append(dict(feature=m.group(1), start=int(m.group(2)), end=int(m.group(3)),
                                label=m.group(1), note="explicit locus"))
            else:
                out.append(dict(feature=s, start=1, end=lens.get(s, 0) or 1,
                                label=s, note="whole feature"))
        return out

    if not a.sites_csv:
        sys.exit("[igv-fig] need --sites-csv (with --accessions/--site-ids/--where-cm-hit) or --locus")

    rows = list(csv.DictReader(open(a.sites_csv)))
    if not rows:
        sys.exit(f"[igv-fig] {a.sites_csv} has no rows")
    cols = rows[0].keys()
    acc_col = "accession" if "accession" in cols else None
    plain_col = "plain_accession" if "plain_accession" in cols else None
    if acc_col is None:
        sys.exit("[igv-fig] sites table has no `accession` column")
    cm_cols = [c for c in cols if c.endswith(".cm_hit")]

    want_acc = set(a.accessions or [])
    want_ids = set(a.site_ids or [])

    picked, seen = [], set()
    for r in rows:
        if want_ids:
            if r.get("site_id", "") not in want_ids:
                continue
        elif want_acc:
            if not ({r.get(acc_col, ""), r.get(plain_col or acc_col, "")} & want_acc):
                continue
        elif a.where_cm_hit:
            if not any((r.get(c) or "").strip() for c in cm_cols):
                continue
        # else: no selector -> every site

        feat = r[acc_col]
        if feat in seen and not a.one_panel_per_site:
            continue
        seen.add(feat)

        flen = lens.get(feat, 0)
        start, end = 1, flen or 1
        if a.pad is not None:
            try:
                off = int(float(r.get("stall_offset_in_feature", "")))
                start = max(1, off - a.pad)
                end = min(flen or off + a.pad, off + a.pad)
            except (TypeError, ValueError):
                pass

        org = (r.get("organism") or r.get("species") or "").strip()
        hits = [c.split(".cm_hit")[0] for c in cm_cols if (r.get(c) or "").strip()]
        picked.append(dict(
            feature=feat, start=start, end=end,
            label=org or (r.get(plain_col or acc_col) or feat),
            note=f"{r.get(plain_col or acc_col, '')} stall {r.get('stall_site_genomic_position', '?')}"
                 f"{'  CM: ' + ','.join(hits) if hits else ''}"))
    if not picked:
        sys.exit("[igv-fig] no sites matched the selection")
    return picked


# ─────────────────────────────────────────────────────────────── session writing


def safe_name(s):
    return re.sub(r"[^A-Za-z0-9._-]+", "_", s).strip("_")[:120]


def build_session(a, loc, ymax, labels, bedgraph_paths):
    """Session XML with an explicit DataRange on every bedGraph track. RZ's make_igv_session.py
    writes the layout; it has no DataRange support, so the tracks are written here and the layout
    follows the same convention (DataPanel of bedGraphs, one Panel per BAM, FeaturePanel last)."""
    locus = f"{loc['feature']}:{loc['start']}-{loc['end']}"
    session = ET.Element("Session", {"genome": os.path.abspath(a.genome), "locus": locus,
                                     "version": "8"})
    res = ET.SubElement(session, "Resources")
    for p in bedgraph_paths + list(a.bam or []) + list(a.gtf or []) + list(a.bed or []) \
            + [a.bed_tiles]:
        ET.SubElement(res, "Resource", {"path": os.path.abspath(p)})

    dp = ET.SubElement(session, "Panel", {"name": "DataPanel"})
    for lbl, p in zip(labels, bedgraph_paths):
        t = ET.SubElement(dp, "Track", {
            "attributeKey": lbl, "clazz": "org.broad.igv.track.DataSourceTrack",
            "id": os.path.abspath(p), "name": lbl, "renderer": "BAR_CHART",
            "visible": "true", "windowFunction": "none",
            # autoScale off is the whole point: the range is locked below
            "autoScale": "false", "color": a.color_treated if lbl.upper().startswith("X")
            else a.color_control})
        ET.SubElement(t, "DataRange", {"baseline": "0", "maximum": f"{ymax:.0f}",
                                       "minimum": "0", "type": "LINEAR"})

    for i, p in enumerate(a.bam or []):
        name = os.path.basename(p)
        panel = ET.SubElement(session, "Panel", {"name": f"Panel_{safe_name(name)}_{i}"})
        ET.SubElement(panel, "Track", {
            "attributeKey": f"{name} Coverage", "clazz": "org.broad.igv.sam.CoverageTrack",
            "id": f"{os.path.abspath(p)}_coverage", "name": f"{name} Coverage",
            "snpThreshold": "0.2", "visible": "true", "autoScale": "false"})
        al = ET.SubElement(panel, "Track", {
            "attributeKey": name, "clazz": "org.broad.igv.sam.AlignmentTrack",
            "color": "185,185,185", "displayMode": "SQUISHED", "experimentType": "OTHER",
            "id": os.path.abspath(p), "name": name, "visible": "true"})
        ET.SubElement(al, "RenderOptions", {"duplicatesOption": "FILTER"})

    fp = ET.SubElement(session, "Panel", {"name": "FeaturePanel"})
    for p in list(a.gtf or []) + list(a.bed or []) + [a.bed_tiles]:
        ET.SubElement(fp, "Track", {
            "attributeKey": os.path.basename(p), "clazz": "org.broad.igv.track.FeatureTrack",
            "displayMode": "EXPANDED", "groupByStrand": "false",
            "id": os.path.abspath(p), "name": os.path.basename(p), "visible": "true"})

    hidden = ET.SubElement(session, "HiddenAttributes")
    for k in ("DATA FILE", "DATA TYPE", "NAME"):
        ET.SubElement(hidden, "Attribute", {"name": k})
    return ET.ElementTree(session), locus


# ─────────────────────────────────────────────────────────────── main


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--genome", required=True, help="ordered pre-tile reference FASTA (needs .fai)")
    ap.add_argument("--bed-tiles", required=True, help="the ordered tile BED (also gives feature lengths)")
    ap.add_argument("--bedgraph", required=True, nargs="+", help="5'-end bedGraphs, sample-sheet order")
    ap.add_argument("--labels", nargs="+", help="track names, same order (default: file stems)")
    ap.add_argument("--gtf", nargs="*", default=[], help="organism-labelled sites GTF from step 13a")
    ap.add_argument("--bed", nargs="*", default=[], help="sites / windows BED from step 13a")
    ap.add_argument("--bam", nargs="*", default=[], help="optional alignment tracks")
    ap.add_argument("--out-dir", required=True)

    sel = ap.add_argument_group("which loci")
    sel.add_argument("--sites-csv", help="*.sites_final.csv")
    sel.add_argument("--accessions", nargs="*", help="plain or feature accessions to make panels for")
    sel.add_argument("--site-ids", nargs="*")
    sel.add_argument("--where-cm-hit", action="store_true", help="every site with any CM hit")
    sel.add_argument("--locus", nargs="*", help="explicit FEATURE or FEATURE:start-end")
    sel.add_argument("--one-panel-per-site", action="store_true",
                     help="default is one panel per feature; this gives one per site")
    sel.add_argument("--pad", type=int, default=None,
                     help="window the locus to stall +/- PAD nt instead of the whole feature")

    rng = ap.add_argument_group("data range")
    rng.add_argument("--ymax-mode", choices=["shared-locus", "shared-global", "fixed"],
                     default="shared-locus",
                     help="shared-locus (default): max across all libraries at that locus. "
                          "shared-global: one range for every panel. fixed: --ymax.")
    rng.add_argument("--ymax", type=float, help="with --ymax-mode fixed")
    rng.add_argument("--ymax-pad", type=float, default=1.08, help="headroom multiplier (default 1.08)")

    ap.add_argument("--color-control", default="120,120,120")
    ap.add_argument("--color-treated", default="181,23,158")
    ap.add_argument("--igv", default="igv.sh", help="IGV launcher, written into the batch script")
    ap.add_argument("--snapshot-format", nargs="+", default=["png", "svg"])
    a = ap.parse_args()

    labels = a.labels or [os.path.splitext(os.path.basename(p))[0] for p in a.bedgraph]
    if len(labels) != len(a.bedgraph):
        sys.exit(f"[igv-fig] {len(a.bedgraph)} bedGraphs but {len(labels)} labels")
    for p in [a.genome, a.bed_tiles] + list(a.bedgraph) + list(a.gtf) + list(a.bed) + list(a.bam):
        if not os.path.exists(p):
            sys.exit(f"[igv-fig] missing: {p}")
    if not os.path.exists(a.genome + ".fai"):
        print(f"[igv-fig] NOTE no {a.genome}.fai — IGV needs it; run: samtools faidx {a.genome}",
              file=sys.stderr)

    os.makedirs(a.out_dir, exist_ok=True)
    print(f"[igv-fig] reading {len(a.bedgraph)} bedGraphs", file=sys.stderr)
    bgs = [read_bedgraph(p) for p in a.bedgraph]

    loci = resolve_loci(a)
    print(f"[igv-fig] {len(loci)} panel(s)", file=sys.stderr)

    g_max = None
    if a.ymax_mode == "shared-global":
        g_max = max(locus_max(bgs, l["feature"]) for l in loci) * a.ymax_pad

    batch, manifest = [], []
    snap_dir = os.path.join(a.out_dir, "snapshots")
    os.makedirs(snap_dir, exist_ok=True)
    batch.append(f"snapshotDirectory {os.path.abspath(snap_dir)}")

    for i, loc in enumerate(loci, 1):
        if a.ymax_mode == "fixed":
            if a.ymax is None:
                sys.exit("[igv-fig] --ymax-mode fixed needs --ymax")
            ymax = a.ymax
        elif a.ymax_mode == "shared-global":
            ymax = g_max
        else:
            ymax = locus_max(bgs, loc["feature"], loc["start"] - 1, loc["end"]) * a.ymax_pad
        ymax = max(ymax, 1.0)

        stem = f"{i:02d}_{safe_name(loc['label'])}"
        xml = os.path.join(a.out_dir, stem + ".xml")
        tree, locus = build_session(a, loc, ymax, labels, list(a.bedgraph))
        ET.indent(tree, space="    ")
        tree.write(xml, encoding="UTF-8", xml_declaration=True)

        batch += [f"new", f"load {os.path.abspath(xml)}", f"goto {locus}",
                  "maxPanelHeight 800"]
        for fmt in a.snapshot_format:
            batch.append(f"snapshot {stem}.{fmt}")
        manifest.append(dict(panel=i, label=loc["label"], feature=loc["feature"],
                             locus=locus, ymax=round(ymax, 1), session=os.path.abspath(xml),
                             note=loc["note"]))
        print(f"  {i:02d}  {loc['label'][:42]:<42} {locus:<58} ymax {ymax:>9.0f}")

    batch.append("exit")
    bpath = os.path.join(a.out_dir, "snapshots.igv_batch")
    open(bpath, "w").write("\n".join(batch) + "\n")

    mpath = os.path.join(a.out_dir, "panels.tsv")
    with open(mpath, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(manifest[0]), delimiter="\t")
        w.writeheader(); w.writerows(manifest)

    print(f"\n[igv-fig] {len(loci)} session(s) -> {os.path.abspath(a.out_dir)}")
    print(f"[igv-fig] panel manifest (locus and locked ymax per panel) -> {mpath}")
    print(f"[igv-fig] batch script -> {bpath}")
    print(f"\nrender all panels headlessly:\n  {a.igv} --batch {os.path.abspath(bpath)}")
    print(f"snapshots land in {os.path.abspath(snap_dir)}")
    print("\nymax mode: " + a.ymax_mode +
          ". Every bedGraph track has autoScale=false and an explicit DataRange, so X and R "
          "are on the same axis and panel heights are comparable.")


if __name__ == "__main__":
    main()
